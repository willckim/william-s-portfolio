def episodes_list(model: dict) -> str:
    items = []
    for i, ep in enumerate(model["materials"]["episodes"]):
        metals = ", ".join(f"{k} {100 * v:+.1f}%" for k, v in ep["metals_log_change"].items())
        actions = (" Federal Register actions in the window: " + ", ".join(e(a) for a in ep["actions"]) + "."
                   if ep["actions"] else "")
        items.append(f'<li><strong>{e(ep["label"])}{" (default)" if i == 0 else ""}.</strong> {month(ep["from"])} to '
                     f'{month(ep["to"])}. Log change {metals}. Through the pass-through coefficients that is '
                     f'{100 * ep["ppi_effect"]:.2f}% on the construction input PPI. {e(ep["basis"])}{actions}</li>')
    return "<ul>" + "".join(items) + "</ul>"


