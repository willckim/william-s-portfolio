def macro_chart(macro: dict) -> str:
    """Recent actuals and the published forecast with its P10 to P90 range of past misses."""
    actual = macro["recent_actuals"]
    fc = macro["published"]["forecast"]
    W, H, L, R, T, B = 640, 300, 64, 16, 16, 40
    values = [a["value"] for a in actual] + [f["p10"] for f in fc] + [f["p90"] for f in fc]
    step = 10000
    y0, y1 = (min(values) // step) * step, (max(values) // step + 1) * step
    # The forecast starts after the publication-lag month, which is left blank
    # rather than drawn as if it were known.
    index = lambda ym: int(ym[:4]) * 12 + int(ym[5:7])  # noqa: E731
    first_fc = len(actual) - 1 + index(fc[0]["date"]) - index(actual[-1]["date"])
    n = first_fc + len(fc)
    x = lambda i: L + i / (n - 1) * (W - L - R)  # noqa: E731
    y = lambda v: T + (y1 - v) / (y1 - y0) * (H - T - B)  # noqa: E731
    out = [f'<svg class="chart" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-labelledby="cfm-t cfm-d">',
           '<title id="cfm-t">U.S. private nonresidential construction spending, actual and forecast</title>',
           f'<desc id="cfm-d">Monthly spending, not seasonally adjusted, in millions of dollars. Actual data from '
           f'{month(actual[0]["date"][:7])} to {month(actual[-1]["date"][:7])}, ending at {actual[-1]["value"]:,.0f}. '
           f'Published forecast from {month(fc[0]["date"][:7])} to {month(fc[-1]["date"][:7])}: '
           f'{fc[0]["point"]:,.0f} in the first month and {fc[-1]["point"]:,.0f} in the last, with a P10 to P90 range of past '
           f'misses from {fc[-1]["p10"]:,.0f} to {fc[-1]["p90"]:,.0f} in the last month. The numbers are in the table below.</desc>']
    v = y0
    while v <= y1:
        out.append(f'<line class="ch-grid" x1="{L}" x2="{W - R}" y1="{y(v):.1f}" y2="{y(v):.1f}"/>'
                   f'<text class="ch-tick" x="{L - 8}" y="{y(v) + 4:.1f}" text-anchor="end">${v / 1000:,.0f}B</text>')
        v += step
    labels = [(i, a["date"][:7]) for i, a in enumerate(actual)] + [(first_fc + j, f["date"][:7]) for j, f in enumerate(fc)]
    for i, ym in labels:
        if ym[5:7] == "01":
            out.append(f'<text class="ch-tick" x="{x(i):.1f}" y="{H - B + 20}" text-anchor="middle">{ym[:4]}</text>')
    band = ([f"{x(first_fc + j):.1f} {y(f['p90']):.1f}" for j, f in enumerate(fc)]
            + [f"{x(first_fc + j):.1f} {y(f['p10']):.1f}" for j, f in reversed(list(enumerate(fc)))])
    out.append(f'<path class="cf-band" d="M{" L".join(band)} Z"/>')
    out.append('<path class="ch-line cf-actual" d="M' + " L".join(f"{x(i):.1f} {y(a['value']):.1f}"
                                                                for i, a in enumerate(actual)) + '"/>')
    out.append('<path class="ch-line cf-scen" d="M' + " L".join(f"{x(first_fc + j):.1f} {y(f['point']):.1f}"
                                                              for j, f in enumerate(fc)) + '"/>')
    out.append("</svg>")
    return "".join(out)


