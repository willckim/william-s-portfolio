"""The Construction Forecast panel: its static HTML region and its data file.

Called by sitegen.py. Input is tools/data/construction.json, written by
tools/extract_construction.py from the forecasting engine's committed results.

    construction_js()      -> assets/lab/construction-data.js (the scenario model the page computes with)
    construction_region()  -> the <!-- gen:construction --> region of lab.html

Every number here is read from that file. The static region carries the
controls, the "How it works" tables, a no-script fallback of every preset, and
the real macro forecast as inline SVG, so the page reads in full without
JavaScript. assets/lab/construction.js draws the scenario charts.

The region is checked against the site's copy rules before it is returned, so a
semicolon or an em dash in a source title stops the build instead of shipping.
"""

