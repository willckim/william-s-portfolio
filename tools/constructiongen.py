def verify_why(con: dict) -> None:
    """The panel says funding timing moves the 12-month revenue the most. Prove it from the presets."""
    main = str(con["model"]["main_months"])
    moves = {k: abs(r["change_from_base"][main]["revenue"]) for k, r in con["reference"].items() if k != "base"}
    if max(moves, key=moves.get) != "funding_delayed":
        raise SystemExit(f"the panel's sentence about funding timing is no longer true: {moves}")


def check_copy(html: str) -> None:
    text = unescape(re.sub(r"<[^>]+>", " ", html))            # what a reader sees, entities decoded
    for name, pattern in BANNED:
        hit = re.search(pattern, text)
        if hit:
            raise SystemExit(f"construction panel copy has a {name}: ...{text[max(0, hit.start() - 60):hit.end() + 20]}...")
