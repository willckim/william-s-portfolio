def defaults_sentence(d: dict) -> str:
    """One plain sentence on the difference that stays on purpose, built from the data."""
    main = next(x for x in d["samples"]["samples"] if x.get("settings"))
    general = next(x for x in d["samples"]["samples"] if not x.get("settings"))["result"]
    first, lag = main["settings"]["first_origin"], main["settings"]["publication_lag"]
    return (f"Your own files and the other samples are tested from the last {general['origins']} months with no "
            f"publication lag, because the page cannot know when your data is published, while the "
            f"{e(main['label'].lower())} sample uses the main forecast's settings, origins from "
            f"{MONTHS[first[1] - 1]} {first[0]} and data known {lag} month late, so both tabs show the same winner "
            f"and errors.")


