OPS = {">": "above", ">=": "at or above", "<": "below", "<=": "at or below"}
UNITS = {"PRCP": " in of precipitation", "TMAX": "°F max temperature", "TMIN": "°F min temperature",
         "SNWD": " in of snow on the ground", "WSF2": " mph fastest 2-minute wind"}


def rule_text(element: str, op: str, threshold) -> str:
    return f"{OPS[op].capitalize()} {threshold:g}{UNITS[element]}"


